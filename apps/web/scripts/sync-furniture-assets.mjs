import { access, mkdir, readFile, readdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { computeFurnitureAssetContractHash, readFurniturePackageContractSources, validateFurnitureAssetManifest } from "./furniture-asset-contract.mjs";

const root = process.cwd();
const assetsRoot = path.resolve(root, "lib", "bedroom", "assets");
const registryRoot = path.join(assetsRoot, "registry");
const scopes = [
  { name: "builtin", root: path.join(assetsRoot, "builtin") },
  { name: "user-generated", root: path.join(assetsRoot, "user-generated") },
];
const checkOnly = process.argv.includes("--check");
const idPattern = /^[a-z0-9][a-z0-9-]{1,63}$/;

async function exists(filePath) {
  try { await access(filePath); return true; }
  catch (error) { if (error?.code === "ENOENT") return false; throw error; }
}

async function loadPackages() {
  const packages = [];
  for (const scope of scopes) {
    if (!(await exists(scope.root))) continue;
    const entries = await readdir(scope.root, { withFileTypes: true });
    for (const entry of entries.sort((left, right) => left.name.localeCompare(right.name))) {
      if (!entry.isDirectory()) continue;
      const directory = path.join(scope.root, entry.name);
      const manifestPath = path.join(directory, "asset.json");
      const runtimePath = path.join(directory, "runtime.ts");
      if (!(await exists(manifestPath))) continue;
      if (!(await exists(runtimePath))) throw new Error(`${scope.name}/${entry.name} 缺少固定入口 runtime.ts`);
      const manifest = JSON.parse(await readFile(manifestPath, "utf8"));
      if (!idPattern.test(manifest.id) || manifest.id !== entry.name) throw new Error(`资产目录与 id 不一致: ${scope.name}/${entry.name}`);
      if (manifest.assetScope !== scope.name) throw new Error(`${manifest.id} 的 assetScope 必须是 ${scope.name}`);
      for (const obsolete of ["factoryFile", "factoryExport", "runtimeFactoryFile", "runtimeFactoryExport"]) if (obsolete in manifest) throw new Error(`${manifest.id} 不得声明旧字段 ${obsolete}`);
      const issues = validateFurnitureAssetManifest(manifest);
      if (issues.length) throw new Error(`${manifest.id} 的家具资产契约无效: ${issues.join("; ")}`);
      const modelPath = path.join(directory, "model.ts");
      const hasModel = await exists(modelPath);
      const directRuntimeSource = await readFile(runtimePath, "utf8");
      if (!/export\s+(?:async\s+)?(?:function|const)\s+createFurnitureModel\b|export\s*\{[^}]*\bas\s+createFurnitureModel\b/s.test(directRuntimeSource)) throw new Error(`${manifest.id} 的 runtime.ts 必须导出 createFurnitureModel`);
      if (hasModel) {
        const directModelSource = await readFile(modelPath, "utf8");
        if (!/export\s+(?:async\s+)?(?:function|const)\s+createSourceModel\b|export\s*\{[^}]*\bas\s+createSourceModel\b/s.test(directModelSource)) throw new Error(`${manifest.id} 的 model.ts 必须导出 createSourceModel`);
      }
      const { modelSource, runtimeSource } = await readFurniturePackageContractSources(directory);
      packages.push({ manifest, scope: scope.name, hasModel, hash: computeFurnitureAssetContractHash(modelSource, runtimeSource, manifest) });
    }
  }
  const duplicate = packages.find((entry, index) => packages.findIndex((candidate) => candidate.manifest.id === entry.manifest.id) !== index);
  if (duplicate) throw new Error(`家具资产 id 在不同范围重复: ${duplicate.manifest.id}`);
  return packages;
}

const importPath = (asset, file) => `../${asset.scope}/${asset.manifest.id}/${file}`;

function renderCatalog(packages) {
  const lines = ["/* This file is generated by scripts/sync-furniture-assets.mjs. */"];
  packages.forEach((asset, index) => lines.push(`import manifest${index} from "${importPath(asset, "asset.json")}";`));
  lines.push('import type { FurnitureAssetCatalogEntry } from "../package-types";', 'import type { FurnitureAssetManifestV3 } from "../manifest-types";', "");
  lines.push("export const FURNITURE_PACKAGE_CATALOG: FurnitureAssetCatalogEntry[] = [");
  packages.forEach((asset, index) => lines.push(`  { manifest: manifest${index} as FurnitureAssetManifestV3, contractHash: "${asset.hash}" },`));
  lines.push("];", "");
  lines.push('export const BUILTIN_PACKAGE_CATALOG = FURNITURE_PACKAGE_CATALOG.filter((entry) => entry.manifest.assetScope === "builtin");');
  lines.push('export const USER_GENERATED_PACKAGE_CATALOG = FURNITURE_PACKAGE_CATALOG.filter((entry) => entry.manifest.assetScope === "user-generated");', "");
  return lines.join("\n");
}

function renderRuntimeLoaders(packages) {
  const lines = ["/* This file is generated by scripts/sync-furniture-assets.mjs. */", 'import type { FurnitureRuntimeFactory, FurnitureRuntimeLoader } from "../runtime-types";', "", "export const FURNITURE_PACKAGE_RUNTIME_LOADERS: Record<string, FurnitureRuntimeLoader> = {"];
  for (const asset of packages) lines.push(`  "${asset.manifest.id}": () => import("${importPath(asset, "runtime")}").then((module) => ({ createFurnitureModel: module.createFurnitureModel as FurnitureRuntimeFactory })),`);
  lines.push("};", "");
  return lines.join("\n");
}

function renderModelLoaders(packages) {
  const lines = ["/* This file is generated by scripts/sync-furniture-assets.mjs. */", 'import type { FurnitureSourceModelFactory, FurnitureSourceModelLoader } from "../package-types";', "", "export const FURNITURE_SOURCE_MODEL_LOADERS: Record<string, FurnitureSourceModelLoader> = {"];
  for (const asset of packages.filter((entry) => entry.hasModel)) lines.push(`  "${asset.manifest.id}": () => import("${importPath(asset, "model")}").then((module) => ({ createSourceModel: module.createSourceModel as FurnitureSourceModelFactory })),`);
  lines.push("};", "");
  return lines.join("\n");
}

const packages = await loadPackages();
const outputs = new Map([
  [path.join(registryRoot, "catalog.generated.ts"), renderCatalog(packages)],
  [path.join(registryRoot, "runtime-loaders.generated.ts"), renderRuntimeLoaders(packages)],
  [path.join(registryRoot, "model-loaders.generated.ts"), renderModelLoaders(packages)],
]);
if (!checkOnly) await mkdir(registryRoot, { recursive: true });
let stale = false;
for (const [filePath, expected] of outputs) {
  const current = await exists(filePath) ? await readFile(filePath, "utf8") : "";
  if (current === expected) continue;
  stale = true;
  if (!checkOnly) await writeFile(filePath, expected, "utf8");
}
if (stale && checkOnly) { console.error("家具资产注册表已过期，请运行 npm run assets:sync。"); process.exit(1); }
if (stale) console.log("家具资产注册表已同步。");
