import { createHash } from "node:crypto";
import { access, readFile, readdir, writeFile } from "node:fs/promises";
import path from "node:path";

const root = process.cwd();
const generatedRoot = path.resolve(root, "lib", "bedroom", "generated");
const registryPath = path.join(generatedRoot, "registry.generated.ts");
const checkOnly = process.argv.includes("--check");
const idPattern = /^[a-z0-9][a-z0-9-]{1,63}$/;
const exportPattern = /^[A-Za-z_$][A-Za-z0-9_$]*$/;

async function exists(filePath) {
  try {
    await access(filePath);
    return true;
  } catch (error) {
    if (error?.code === "ENOENT") return false;
    throw error;
  }
}

async function loadAssets() {
  const entries = await readdir(generatedRoot, { withFileTypes: true });
  const assets = [];
  for (const entry of entries.sort((a, b) => a.name.localeCompare(b.name))) {
    if (!entry.isDirectory()) continue;
    const manifestPath = path.join(generatedRoot, entry.name, "asset.json");
    if (!(await exists(manifestPath))) continue;
    const manifest = JSON.parse(await readFile(manifestPath, "utf8"));
    if (!idPattern.test(manifest.id) || manifest.id !== entry.name) throw new Error(`Invalid generated asset id: ${manifest.id ?? entry.name}`);
    if (!exportPattern.test(manifest.factoryExport)) throw new Error(`Invalid factory export for ${manifest.id}`);
    const factoryPath = path.resolve(path.dirname(manifestPath), manifest.factoryFile);
    if (path.dirname(factoryPath) !== path.dirname(manifestPath) || !factoryPath.endsWith(".ts")) throw new Error(`Factory path must stay inside ${manifest.id}`);
    const factorySource = await readFile(factoryPath, "utf8");
    // Git normalizes text files to LF in GitHub Actions, while Windows
    // checkouts may use CRLF. Hash normalized text so the generated registry
    // remains stable across platforms.
    const normalizedFactorySource = factorySource.replace(/\r\n/g, "\n");
    assets.push({
      manifest,
      hash: createHash("sha256").update(normalizedFactorySource).digest("hex"),
      importPath: `./${entry.name}/${path.basename(manifest.factoryFile, ".ts")}`,
    });
  }
  return assets;
}

function renderRegistry(assets) {
  const lines = ["/* This file is generated by scripts/sync-generated-assets.mjs. */"];
  assets.forEach((asset, index) => {
    lines.push(`import manifest${index} from "./${asset.manifest.id}/asset.json";`);
    lines.push(`import { ${asset.manifest.factoryExport} as factory${index} } from "${asset.importPath}";`);
  });
  lines.push('import type { GeneratedAssetManifest, GeneratedAssetModule, GeneratedModelFactory } from "./types";', "");
  lines.push("export const GENERATED_ASSET_MODULES: GeneratedAssetModule[] = [");
  assets.forEach((asset, index) => {
    lines.push("  {");
    lines.push(`    manifest: manifest${index} as GeneratedAssetManifest,`);
    lines.push(`    factory: factory${index} as GeneratedModelFactory,`);
    lines.push(`    factoryHash: "${asset.hash}",`);
    lines.push("  },");
  });
  lines.push("];", "");
  return lines.join("\n");
}

const expected = renderRegistry(await loadAssets());
const current = (await exists(registryPath)) ? await readFile(registryPath, "utf8") : "";
if (current === expected) process.exit(0);
if (checkOnly) {
  console.error("Generated asset registry is stale. Run npm run assets:sync.");
  process.exit(1);
}
await writeFile(registryPath, expected, "utf8");
console.log("Generated asset registry synchronized.");
